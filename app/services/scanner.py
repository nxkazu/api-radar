logger = logging.getLogger(__name__)

ClientFactory = Callable[[], GitHubClient]


def _slug(value: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")
    return slug[:60] or "spec"


def _now() -> datetime:
    return datetime.now(UTC)


def create_scan(session: Session, spec_id: int, trigger: str) -> Scan:
    spec = session.get(Spec, spec_id)
    if spec is None:
        raise ValueError(f"spec {spec_id} does not exist")
    scan = Scan(spec_id=spec_id, trigger=trigger, status="queued")
    session.add(scan)
    session.flush()
    return scan


def _baseline_report(spec: Spec, head: ParsedSpec) -> str:
    return (
        f"# API Radar report — {spec.name}\n\n"
        f"Baseline recorded for `{spec.source}` "
        f"(version `{head.version or '?'}`, sha256 `{head.sha256[:12]}`).\n\n"
        "No previous snapshot existed, so there is nothing to diff yet. "
        "The next scan will compare against this snapshot.\n"
    )


def _removed_paths(diff: DiffResult) -> list[str]:
    paths: set[str] = set()
    for change in diff.changes:
        if change.kind == "operation.removed" and " " in change.location:
            paths.add(change.location.split(" ", 1)[1])
    return sorted(paths)


def _pr_body(diff: DiffResult, spec: Spec, report_path: str) -> str:
    counts = diff.counts()
    lines = [
        f"API Radar detected **{counts['breaking']} breaking** change(s) in `{spec.name}` "
        f"({diff.base_version} → {diff.head_version}).",
        "",
        "| Severity | Count |",
        "|---|---:|",
        f"| Breaking | {counts['breaking']} |",
        f"| Needs review | {counts['risky']} |",
        f"| Non-breaking | {counts['non_breaking']} |",
        "",
        f"Full report: `{report_path}`",
        "",
    ]
    breaking = diff.breaking
    if breaking:
        lines += ["### Breaking changes", ""]
        for change in breaking[:15]:
            lines.append(f"- **{change.location}** — {change.message}")
        if len(breaking) > 15:
            lines.append(f"- …and {len(breaking) - 15} more (see the report)")
        lines.append("")
    lines += [
        "---",
        "",
        "Generated by [API Radar](https://github.com/nxkazu/api-radar). "
        "Mechanical path rewrites are included when they could be applied safely; "
        "review the diff and let CI run before merging.",
    ]
    return "\n".join(lines)


def _collect_call_sites(
    client: GitHubClient,
    repository: Repository,
    base: ParsedSpec,
    head: ParsedSpec,
    diff: DiffResult,
    settings,
) -> tuple[dict[str, list[tuple[str, int]]], dict[str, list[CallSite]], list[PathRename], list]:
    client.authenticate_for_repo(repository.full_name, repository.installation_id)
    files = client.fetch_text_files(
        repository.full_name,
        repository.default_branch,
        max_files=settings.max_repo_files,
        max_file_bytes=settings.max_file_bytes,
    )
    renames = detect_renames(base.document, head.document)
    paths = sorted(set(_removed_paths(diff)) | {rename.old for rename in renames})
    inventory = find_references(paths, files) if paths else {}
    patches = plan_renames(
        renames,
        files,
        max_file_bytes=settings.max_file_bytes,
        max_files=settings.max_patch_files,
    )
    call_sites = {
        path: [(site.file, site.line) for site in sites]
        for path, sites in inventory.items()
        if sites
    }
    return call_sites, inventory, renames, patches


def _open_migration_pr(
    *,
    client: GitHubClient,
    repository: Repository,
    spec: Spec,
    scan: Scan,
    diff: DiffResult,
    report: str,
    patches: list[FilePatch],
) -> None:
    branch = f"apiradar/{_slug(spec.name)}-{scan.id}"
    report_path = (
        f".apiradar/reports/{_slug(spec.name)}-"
        f"{_slug(diff.base_version or 'base')}-to-{_slug(diff.head_version or 'head')}.md"
    )

    files: dict[str, str] = {patch.path: patch.new_content for patch in patches}
    files[report_path] = report

    title = (
        f"[API Radar] {len(diff.breaking)} breaking change(s) in {spec.name} "
        f"({diff.base_version} → {diff.head_version})"
    )
    try:
        client.commit_files(
            repository.full_name,
            branch=branch,
            base_branch=repository.default_branch,
            files=files,
            message=f"API Radar: migrate {spec.name} to {diff.head_version or 'new version'}",
        )
        pull = client.open_pull_request(
            repository.full_name,
            head=branch,
            base=repository.default_branch,
            title=title,
            body=_pr_body(diff, spec, report_path),
        )
        scan.pr_branch = branch
        scan.pr_url = str(pull.get("html_url") or "")
    except GitHubError as exc:
        logger.warning("auto-PR for scan %s failed: %s", scan.id, exc)
        scan.pr_error = str(exc)


def _apply_diff(
    session: Session,
    scan: Scan,
    diff: DiffResult,
) -> None:
    counts = diff.counts()
    scan.breaking_count = counts["breaking"]
    scan.risky_count = counts["risky"]
    scan.non_breaking_count = counts["non_breaking"]
    scan.total_count = counts["total"]
    for change in diff.changes:
        session.add(_change_row(scan.id, change))


def _change_row(scan_id: int, change: DiffChange) -> Change:
    return Change(
        scan_id=scan_id,
        kind=change.kind,
        severity=change.severity,
        location=change.location,
        pointer=change.pointer,
        message=change.message,
        before=change.before,
        after=change.after,
        fix_hint=change.fix_hint,
    )


def execute_scan(
    session: Session,
    scan_id: int,
    *,
    client_factory: ClientFactory | None = None,
    collect_call_sites: bool | None = None,
) -> Scan:
    """Run a queued scan. Errors are recorded on the scan, not raised."""
    settings = get_settings()
    scan = session.get(Scan, scan_id)
    if scan is None:
        raise ValueError(f"scan {scan_id} does not exist")

    spec = session.get(Spec, scan.spec_id)
    if spec is None:
        scan.status = "failed"
        scan.error = "tracked spec no longer exists"
        return scan
    repository = session.get(Repository, spec.repository_id)

    scan.status = "running"
    scan.started_at = _now()
    session.flush()

    client = client_factory() if client_factory else GitHubClient.from_settings()
    if collect_call_sites is None:
        collect_call_sites = settings.auto_pr

    try:
        raw, _blob_sha = fetch_spec_source(spec, repository, client)
        head = parse_spec(raw)
        scan.head_version = head.version
        scan.head_sha = head.sha256

        if not spec.baseline_content:
            spec.baseline_content = raw
            spec.baseline_version = head.version
            spec.baseline_sha = head.sha256
            scan.status = "completed"
            scan.report_md = _baseline_report(spec, head)
            return scan

        base = parse_spec(spec.baseline_content)
        scan.base_version = base.version
        diff = diff_specs(base, head)

        call_sites: dict[str, list[tuple[str, int]]] = {}
        inventory: dict[str, list[CallSite]] = {}
        renames: list[PathRename] = []
        patches: list = []
        if collect_call_sites and diff.has_breaking:
            try:
                call_sites, inventory, renames, patches = _collect_call_sites(
                    client, repository, base, head, diff, settings
                )
            except GitHubError as exc:
                logger.warning("call-site collection failed for %s: %s", repository.full_name, exc)

        report = diff.to_markdown(
            repository=repository.full_name if repository else None,
            spec_name=spec.name,
            source=spec.source,
            call_sites=call_sites,
        )
        scan.report_md = report
        _apply_diff(session, scan, diff)

        if settings.auto_pr and diff.has_breaking and repository is not None:
            _open_migration_pr(
                client=client,
                repository=repository,
                spec=spec,
                scan=scan,
                diff=diff,
                report=report,
                patches=patches,
            )

        spec.baseline_content = raw
        spec.baseline_version = head.version
        spec.baseline_sha = head.sha256
        scan.status = "completed"
        return scan
    except (SpecFetchError, GitHubError) as exc:
        scan.status = "failed"
        scan.error = str(exc)
        return scan
    except Exception as exc:  # pragma: no cover - unexpected, but must be persisted
        logger.exception("scan %s crashed", scan.id)
        scan.status = "failed"
        scan.error = f"{type(exc).__name__}: {exc}"
        return scan
    finally:
        scan.finished_at = _now()
        spec.last_checked_at = scan.finished_at


def queue_scan(session: Session, spec_id: int, trigger: str = "manual") -> Scan:
    """Persist a queued scan, commit it, then dispatch it to Celery.

    If the broker is unreachable the scan runs inline so a local demo works
    without Redis. The returned row is refreshed either way.
    """
    scan = create_scan(session, spec_id, trigger)
    session.commit()

    from ..workers.tasks import scan_spec_task

    try:
        scan_spec_task.delay(scan.id)
    except Exception as exc:  # broker down / not configured
        logger.warning("Celery dispatch failed, running scan inline: %s", exc)
        execute_scan(session, scan.id)
        session.commit()

    session.refresh(scan)
    return scan


def enabled_spec_ids(session: Session) -> list[int]:
    return list(
        session.scalars(select(Spec.id).where(Spec.enabled.is_(True)).order_by(Spec.id)).all()
    )